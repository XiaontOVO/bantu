import { test } from 'node:test';
import assert from 'node:assert/strict';
import { createServerContext } from '../src/server/http/bootstrap.js';
import { communityAgentTools } from '../src/services/personal-agent-community.js';

test('two registered accounts can read posts, favorite independently and import all share days into their own library', async () => {
  const ctx = createServerContext({ seedDemo: false });
  ctx.accounts.register('agent_author', 'test-only-password-1', 'author');
  ctx.accounts.register('agent_reader', 'test-only-password-2', 'reader');
  assert.equal(ctx.accounts.login('agent_reader', 'test-only-password-2'), 'reader');
  const post = ctx.communityService.publishPost('author', { text: '徐汇散步的旅行记录' }, ctx.accounts.nicknameOf('author'));
  ctx.communityService.addComment('author', post.id, { text: '书院很安静' }, ctx.accounts.nicknameOf('author'));
  const refresh = new Set<string>();
  const tools = communityAgentTools(ctx, 'reader', refresh);
  const run = async (name: string, args: Record<string, unknown>) => tools.find(t => t.name === name)!.run(args) as any;
  assert.equal((await run('community.posts', { query: '徐汇' })).items[0].mine, false);
  assert.equal((await run('community.posts', { mine: true })).total, 0);
  assert.equal((await run('community.post_detail', { postId: post.id })).comments.length, 1);
  await run('community.post_favorite', { postId: post.id, favorite: true });
  await run('community.post_favorite', { postId: post.id, favorite: true });
  assert.equal(ctx.favoritesService.listPosts('reader').length, 1);
  assert.equal(ctx.favoritesService.listPosts('author').length, 0);
  await run('community.post_like', { postId: post.id, liked: true });
  await run('community.post_like', { postId: post.id, liked: true });
  assert.equal(ctx.communityService.postDetail(post.id, 'reader')!.likes, 1);
  assert.equal(ctx.communityService.postDetail(post.id, 'author')!.liked, false);
  const guest = communityAgentTools(ctx, 'guest', new Set());
  assert.throws(() => guest.find(t => t.name === 'community.post_favorite')!.run({ postId: post.id, favorite: true }), /登录/);
  const place = (await ctx.fallbackPlaceProvider.search({ cityCode: '310100', query: '', limit: 1 })).places[0];
  const payload = { v: 3, n: '两天徐汇', c: '310100', cn: '上海', days: [{ s: [{ p: place.placeId, n: place.name, la: place.coordinates!.lat, ln: place.coordinates!.lng, m: 60, cc: '310100' }] }, { s: [] }] };
  const body = Buffer.from(JSON.stringify(payload)).toString('base64').replace(/=+$/, '');
  const checksum = ([...body].reduce((sum, ch) => sum + ch.charCodeAt(0), 0) % 1296).toString(36).toUpperCase().padStart(2, '0');
  const share = ctx.communityService.publishPlanShare('author', { name: payload.n, nickname: 'agent_author', cityCode: payload.c, cityLabel: payload.cn, stopCount: 1, code: `BT1-${body}-${checksum}` });
  const result = await run('community.shares', { query: share.shareCode });
  assert.equal(result.total, 1);
  assert.equal(result.items[0].code, undefined, 'large encoded content is not sent to the model');
  const detail = await run('community.share_detail', { shareId: share.id });
  assert.equal(detail.days.length, 2);
  const saved = await run('community.import_share', { shareId: share.shareCode });
  assert.equal(saved.kind, 'scheme');
  assert.equal(saved.days.length, 2);
  assert.equal(saved.days[1].stops.length, 0);
  assert.equal(saved.days[0].stops[0].place.name, place.name);
  assert.equal(ctx.planLibrary.list('author').length, 0);
  assert.equal(ctx.planLibrary.list('reader').length, 1);
  assert.equal(saved.localDate, undefined);
  assert.ok(refresh.has('plans'));
  ctx.communityService.removePlanShare('author', share.id);
  await assert.rejects(run('community.import_share', { shareId: share.id }), /撤回/);
  assert.equal(ctx.planLibrary.list('reader').length, 1);
});
